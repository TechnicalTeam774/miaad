const DICT = { ar: AR, en: EN };

export function lang() {
  return state.settings.lang === 'en' ? 'en' : 'ar';
}

export function t(key, ...args) {
  const d = DICT[lang()];
  const v = d[key] !== undefined ? d[key] : AR[key];
  return typeof v === 'function' ? v(...args) : v;
}

export const dir = () => (lang() === 'ar' ? 'rtl' : 'ltr');
const locale = () => (lang() === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB');

export function fmtTime(hhmmStr) {
  if (!hhmmStr) return '';
  const [h, m] = hhmmStr.split(':').map(Number);
  const d = new Date(2026, 0, 1, h, m);
  return new Intl.DateTimeFormat(locale(), { hour: 'numeric', minute: '2-digit', hour12: true }).format(d);
}

export function fmtClock(ms) {
  const d = new Date(ms);
  return fmtTime(`${pad(d.getHours())}:${pad(d.getMinutes())}`);
}

export function fmtDay(k, opts = { weekday: 'long', day: 'numeric', month: 'long' }) {
  return new Intl.DateTimeFormat(locale(), opts).format(parseKey(k));
}

export function relDay(k, todayK, addDays) {
  if (k === todayK) return t('today');
  if (k === addDays(todayK, 1)) return t('tomorrow');
  if (k === addDays(todayK, -1)) return t('yesterday');
  return fmtDay(k, { weekday: 'long', day: 'numeric', month: 'short' });
}

/** "12 د", "1 س 5 د", "2 ي 3 س" */
export function fmtDur(ms) {
  const mins = Math.max(0, Math.round(ms / 60000));
  const d = Math.floor(mins / 1440);
  const h = Math.floor((mins % 1440) / 60);
  const m = mins % 60;
  if (d) return `${d} ${t('dayW')}${h ? ` ${h} ${t('hour')}` : ''}`;
  if (h) return `${h} ${t('hour')}${m ? ` ${m} ${t('min')}` : ''}`;
  return `${m} ${t('min')}`;
}

export function fmtMins(mins) {
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return h ? t('hoursMins', h, m) : t('minutes', m);
}
